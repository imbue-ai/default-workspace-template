"""The files an app needs outside its own directory, each a pure function of its manifest and its record.

A user app's directory holds everything the app owns. What the workspace needs in order to run
it sits elsewhere, and is generated here rather than written by hand: one supervisord program
per file under ``system/supervisord.conf.d/``, and one symlink under ``.agents/skills/`` for
each skill the app carries. The files are tracked in the workspace repository, so a worker's
worktree has them and nothing regenerates them at boot, and they never enter an app's own
repository.
"""

import os
import shlex
from collections.abc import Mapping
from collections.abc import Sequence
from pathlib import Path
from typing import Final

from imbue.imbue_common.frozen_model import FrozenModel
from loguru import logger
from pydantic import Field

from app_install.paths import APP_SKILLS_DIRNAME
from app_install.paths import APPS_DIRECTORY
from app_install.paths import MANIFEST_FILENAME
from app_install.paths import PYPROJECT_FILENAME
from app_install.paths import SKILL_FILENAME
from app_install.paths import SKILLS_DIRECTORY
from app_install.paths import SUPERVISORD_DROPIN_DIRECTORY
from app_install.paths import app_directory
from app_manifest.manifest import AppManifest
from app_manifest.manifest import scaffold_env_prefix
from app_manifest.records import AppRecord

GENERATED_HEADER_PREFIX: Final[str] = "# Generated by app-install from "
LOOPBACK_HOST: Final[str] = "127.0.0.1"
PORT_PLACEHOLDER: Final[str] = "{port:main}"
HOST_PLACEHOLDER: Final[str] = "{host}"
_WORKSPACE_DIRECTORY: Final[str] = "/home/user/workspace"
# The scripts below are never run from here: each is a word of the program line this module writes, which
# supervisord runs to start the app.
# own-process: wrapper -- tags the program into its memory band and execs it, in the program line supervisord runs
_OOM_TAG_SERVICE: Final[str] = "system/services/oom_priority/bin/oom_tag_service.py"
# own-process: other-tier -- the program line links the app's venv with the system python, before any venv exists
_VENV_LINKS: Final[str] = "system/scripts/workspace_bare_scripts/venv_links.py"
# own-process: other-tier -- the program line registers the app with the system python, before its venv is synced
_FORWARD_PORT: Final[str] = "system/scripts/forward_port.py"
# own-process: wrapper -- loads the app's secret file into its environment and execs it, so no value is in a file
_WITH_SECRETS: Final[str] = "system/scripts/with_secrets.py"
# ``startsecs`` and ``startretries`` bound a crash loop: an app that dies before it has been up this long counts
# as a failed start, so supervisord backs off and gives up rather than restarting it at full speed for as long as
# the workspace lives.
_PROGRAM_SETTINGS: Final[str] = """\
directory={directory}
autostart=true
autorestart=true
startsecs=30
startretries=5
stopasgroup=true
killasgroup=true
stdout_logfile=/var/log/supervisor/{program}-stdout.log
stderr_logfile=/var/log/supervisor/{program}-stderr.log
stdout_logfile_maxbytes=10MB
stderr_logfile_maxbytes=10MB
stdout_logfile_backups=3
stderr_logfile_backups=3
"""


class DerivedFiles(FrozenModel):
    """Everything generated for one app, by repo-root-relative path."""

    text_by_path: dict[str, str] = Field(description="Each generated file's text")
    link_target_by_path: dict[str, str] = Field(description="Each generated symlink's target, relative to the link")


def is_python_app(repo_root: Path, package: str) -> bool:
    """Whether the app is its own uv project, whose programs run from its own ``.venv``."""
    return (app_directory(repo_root, package) / PYPROJECT_FILENAME).is_file()


def app_skill_names(repo_root: Path, package: str) -> tuple[str, ...]:
    """The skills the app carries: each directory under its ``skills/`` that holds a ``SKILL.md``."""
    skills_directory = app_directory(repo_root, package) / APP_SKILLS_DIRNAME
    if not skills_directory.is_dir():
        return ()
    return tuple(sorted(path.name for path in skills_directory.iterdir() if (path / SKILL_FILENAME).is_file()))


def program_names(manifest: AppManifest) -> tuple[str, ...]:
    """The supervisord programs the app runs: its own, then one ``<name>-<role>`` per declared service."""
    return (str(manifest.program), *(f"{manifest.name}-{service.role}" for service in manifest.services))


def _resolve_placeholders(text: str, port: int) -> str:
    return text.replace(PORT_PLACEHOLDER, str(port)).replace(HOST_PLACEHOLDER, LOOPBACK_HOST)


def _package_relative_directory(package: str) -> str:
    return (APPS_DIRECTORY / package).as_posix()


def _entry_argv(command: str, package: str, is_python: bool) -> list[str]:
    # A Python app's command is a script of its own project, run from its own venv and never through
    # `uv run`, so no uv process stays resident as the program's parent.
    if is_python:
        return [f"{_package_relative_directory(package)}/.venv/bin/{command}"]
    return [command]


def _wrapped_in_secrets(argv: Sequence[str], secret_files: Sequence[str]) -> list[str]:
    """``argv`` run under ``with_secrets.py`` once per declared secret file, so each file's variables reach it and
    no value appears in a config file or a command line."""
    wrapped = list(argv)
    for secret_file in reversed(secret_files):
        wrapped = ["python3", _WITH_SECRETS, f"data/.secrets/{secret_file}.env", "--", *wrapped]
    return wrapped


def _command_line(band: str, steps: Sequence[Sequence[str]]) -> str:
    """The ``command=`` value: the steps chained in one ``bash -c``, since supervisord execs a command directly
    and has no ``&&`` of its own, with the last step replacing the shell."""
    words_by_step = [[shlex.quote(word) for word in step] for step in steps]
    script = " && ".join(" ".join(words) for words in words_by_step[:-1] + [["exec", *words_by_step[-1]]])
    # Inside the double quotes supervisord's parser unescapes a backslash and a quote; a percent sign is its own
    # expansion character.
    quoted_script = script.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return f'python3 {_OOM_TAG_SERVICE} {band} bash -c "{quoted_script}"'


def _quoted_environment_value(value: str) -> str:
    # supervisord reads an environment value as one quoted token with no escapes, so the value is wrapped in
    # whichever quote it does not hold; the manifest refuses a value that holds both. A percent sign is
    # supervisord's own expansion character.
    quote = "'" if '"' in value else '"'
    return quote + value.replace("%", "%%") + quote


def _environment_line(environment: Mapping[str, str]) -> str:
    if not environment:
        return ""
    pairs = ",".join(f"{name}={_quoted_environment_value(value)}" for name, value in sorted(environment.items()))
    return f"environment={pairs}\n"


def _setup_steps(package: str, is_python: bool) -> list[list[str]]:
    """What runs before a Python app's program: link its venv (a rebuilt root filesystem loses the link's target,
    and uv refuses a dangling one), then sync it from the app's own lock, which fails the start on a stale lock."""
    if not is_python:
        return []
    relative = _package_relative_directory(package)
    return [
        ["python3", _VENV_LINKS, "ensure-project", relative],
        ["uv", "sync", "--locked", "--project", relative],
    ]


def _program_conf(
    program: str,
    manifest_relative_path: str,
    band: str,
    steps: Sequence[Sequence[str]],
    environment: Mapping[str, str],
) -> str:
    header = (
        f"{GENERATED_HEADER_PREFIX}{manifest_relative_path} and the app's record.\n"
        "# Do not edit this file: change the manifest and run `uv run --no-sync app-install regenerate`.\n"
    )
    return (
        header
        + f"[program:{program}]\n"
        + f"command={_command_line(band, steps)}\n"
        + _environment_line(environment)
        + _PROGRAM_SETTINGS.format(directory=_WORKSPACE_DIRECTORY, program=program)
    )


def derive_files(repo_root: Path, record: AppRecord, manifest: AppManifest) -> DerivedFiles:
    """Everything the workspace needs outside the app's directory in order to run the app and find its skills."""
    package = record.package
    is_python = is_python_app(repo_root, package)
    manifest_relative_path = f"{_package_relative_directory(package)}/{MANIFEST_FILENAME}"
    band = str(manifest.priority)
    secret_files = [str(secret.file) for secret in manifest.secrets]
    setup_steps = _setup_steps(package, is_python)
    text_by_path: dict[str, str] = {}

    # The main program registers the manifest and the port before it starts, which is how the shell, the
    # forwarder, and the evals evidence capture learn which program serves the app.
    main_command = (
        str(manifest.run.command) if manifest.run is not None and manifest.run.command else str(manifest.name)
    )
    main_args = manifest.run.args if manifest.run is not None else ()
    main_environment = (
        dict(manifest.run.env)
        if manifest.run is not None
        else {f"{scaffold_env_prefix(manifest.name)}_PORT": PORT_PLACEHOLDER}
    )
    main_argv = _entry_argv(main_command, package, is_python) + [
        _resolve_placeholders(argument, record.port) for argument in main_args
    ]
    registration = [
        "python3",
        _FORWARD_PORT,
        "--manifest",
        manifest_relative_path,
        "--url",
        f"http://localhost:{record.port}",
    ]
    main_program = str(manifest.program)
    text_by_path[(SUPERVISORD_DROPIN_DIRECTORY / f"{main_program}.conf").as_posix()] = _program_conf(
        main_program,
        manifest_relative_path,
        band,
        [*setup_steps, registration, _wrapped_in_secrets(main_argv, secret_files)],
        {name: _resolve_placeholders(value, record.port) for name, value in main_environment.items()},
    )

    for service in manifest.services:
        service_program = f"{manifest.name}-{service.role}"
        service_argv = _entry_argv(str(service.command), package, is_python) + [
            _resolve_placeholders(argument, record.port) for argument in service.args
        ]
        text_by_path[(SUPERVISORD_DROPIN_DIRECTORY / f"{service_program}.conf").as_posix()] = _program_conf(
            service_program,
            manifest_relative_path,
            band,
            [*setup_steps, _wrapped_in_secrets(service_argv, secret_files)],
            {name: _resolve_placeholders(value, record.port) for name, value in service.env.items()},
        )

    link_target_by_path = {
        (
            SKILLS_DIRECTORY / skill
        ).as_posix(): f"../../{_package_relative_directory(package)}/{APP_SKILLS_DIRNAME}/{skill}"
        for skill in app_skill_names(repo_root, package)
    }
    return DerivedFiles(text_by_path=text_by_path, link_target_by_path=link_target_by_path)


def _is_generated_for(path: Path, package: str) -> bool:
    try:
        first_line = path.read_text(encoding="utf-8").split("\n", 1)[0]
    except (OSError, UnicodeDecodeError) as e:
        logger.debug("Not treating {} as generated, since it cannot be read: {}", path, e)
        return False
    return first_line.startswith(
        f"{GENERATED_HEADER_PREFIX}{_package_relative_directory(package)}/{MANIFEST_FILENAME} "
    )


def _is_link_into(path: Path, package: str) -> bool:
    return path.is_symlink() and os.readlink(path).startswith(
        f"../../{_package_relative_directory(package)}/{APP_SKILLS_DIRNAME}/"
    )


def existing_derived_paths(repo_root: Path, package: str) -> tuple[str, ...]:
    """The derived files the tree holds for the app now, whatever the manifest says today: every program file
    generated from its manifest and every skill link into its directory."""
    paths: list[str] = []
    dropin_directory = repo_root / SUPERVISORD_DROPIN_DIRECTORY
    if dropin_directory.is_dir():
        paths.extend(
            path.relative_to(repo_root).as_posix()
            for path in sorted(dropin_directory.glob("*.conf"))
            if path.is_file() and _is_generated_for(path, package)
        )
    skills_directory = repo_root / SKILLS_DIRECTORY
    if skills_directory.is_dir():
        paths.extend(
            path.relative_to(repo_root).as_posix()
            for path in sorted(skills_directory.iterdir())
            if _is_link_into(path, package)
        )
    return tuple(paths)


def describe_differences(repo_root: Path, package: str, derived: DerivedFiles) -> tuple[str, ...]:
    """How the tree differs from what the generator writes for the app; empty when it matches."""
    differences: list[str] = []
    for relative_path, text in sorted(derived.text_by_path.items()):
        path = repo_root / relative_path
        if not path.is_file():
            differences.append(f"{relative_path} is missing")
        elif path.read_text(encoding="utf-8") != text:
            differences.append(f"{relative_path} differs from what its manifest generates")
    for relative_path, target in sorted(derived.link_target_by_path.items()):
        path = repo_root / relative_path
        if not path.is_symlink():
            differences.append(f"{relative_path} is not the link to the app's skill")
        elif os.readlink(path) != target:
            differences.append(f"{relative_path} links to {os.readlink(path)} rather than {target}")
    expected = set(derived.text_by_path) | set(derived.link_target_by_path)
    differences.extend(
        f"{relative_path} is generated for the app but its manifest no longer calls for it"
        for relative_path in existing_derived_paths(repo_root, package)
        if relative_path not in expected
    )
    return tuple(differences)


def write_derived_files(repo_root: Path, package: str, derived: DerivedFiles) -> tuple[str, ...]:
    """Bring the tree in line with ``derived``, removing what was generated for the app before and is no longer
    called for; returns the paths that changed."""
    changed: list[str] = []
    expected = set(derived.text_by_path) | set(derived.link_target_by_path)
    for relative_path in existing_derived_paths(repo_root, package):
        if relative_path not in expected:
            (repo_root / relative_path).unlink()
            changed.append(relative_path)
    for relative_path, text in sorted(derived.text_by_path.items()):
        path = repo_root / relative_path
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        changed.append(relative_path)
    for relative_path, target in sorted(derived.link_target_by_path.items()):
        path = repo_root / relative_path
        if path.is_symlink() and os.readlink(path) == target:
            continue
        if path.is_symlink():
            path.unlink()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.symlink_to(target)
        changed.append(relative_path)
    return tuple(changed)
