def test_each_skill_the_app_carries_gets_a_link_a_harness_can_follow(tmp_path: Path) -> None:
    package = write_user_app(tmp_path, "notes")
    write_app_file(tmp_path, package, "skills/weekly-review/SKILL.md", "# Weekly review\n")
    write_app_file(tmp_path, package, "skills/notes-import/SKILL.md", "# Import\n")
    write_app_file(tmp_path, package, "skills/README.md", "not a skill\n")
    write_app_file(tmp_path, package, "skills/drafts/notes.md", "a directory with no SKILL.md is not a skill\n")
    manifest = load_manifest(tmp_path / "system" / "apps" / package / "app.toml")
    record = AppRecord(name=manifest.name, package=package, port=8084, origin=AppOrigin.LOCAL)

    derived = derive_files(tmp_path, record, manifest)
    write_derived_files(tmp_path, package, derived)

    assert derived.link_target_by_path == {
        ".agents/skills/notes-import": "../../system/apps/notes/skills/notes-import",
        ".agents/skills/weekly-review": "../../system/apps/notes/skills/weekly-review",
    }
    assert (tmp_path / ".agents" / "skills" / "weekly-review" / "SKILL.md").read_text() == "# Weekly review\n"


def test_writing_brings_the_tree_in_line_and_a_second_write_changes_nothing(tmp_path: Path) -> None:
    package, _, _, derived = _derive(tmp_path, "notes", 8090, _RUN_SERVICES_AND_SECRETS)

    first = write_derived_files(tmp_path, package, derived)
    second = write_derived_files(tmp_path, package, derived)

    assert sorted(first) == ["system/supervisord.conf.d/notes-indexer.conf", "system/supervisord.conf.d/notes.conf"]
    assert second == ()
    assert describe_differences(tmp_path, package, derived) == ()


def test_a_service_or_skill_the_manifest_dropped_is_removed_and_a_hand_edit_is_reported(tmp_path: Path) -> None:
    package, record, _, derived = _derive(tmp_path, "notes", 8090, _RUN_SERVICES_AND_SECRETS)
    write_app_file(tmp_path, package, "skills/weekly-review/SKILL.md", "# Weekly review\n")
    manifest = load_manifest(tmp_path / "system" / "apps" / package / "app.toml")
    write_derived_files(tmp_path, package, derive_files(tmp_path, record, manifest))
    # A neighbour's hand-written program, which is none of this app's.
    neighbour = tmp_path / "system" / "supervisord.conf.d" / "share-gateway.conf"
    neighbour.write_text("[program:share-gateway]\ncommand=share-gateway\n")

    # The app drops its service and its skill, and someone edits its program file by hand.
    (tmp_path / "system" / "apps" / package / "app.toml").write_text(
        'name = "notes"\ndisplay_name = "Notes"\nicon = "icon.svg"\n'
    )
    (tmp_path / "system" / "apps" / package / "skills" / "weekly-review" / "SKILL.md").unlink()
    main_conf = tmp_path / "system" / "supervisord.conf.d" / "notes.conf"
    main_conf.write_text(main_conf.read_text().replace("startsecs=30", "startsecs=1"))
    slimmer = derive_files(tmp_path, record, load_manifest(tmp_path / "system" / "apps" / package / "app.toml"))

    differences = describe_differences(tmp_path, package, slimmer)
    changed = write_derived_files(tmp_path, package, slimmer)

    assert differences == (
        "system/supervisord.conf.d/notes.conf differs from what its manifest generates",
        "system/supervisord.conf.d/notes-indexer.conf is generated for the app but its manifest no longer calls for it",
        ".agents/skills/weekly-review is generated for the app but its manifest no longer calls for it",
    )
    assert sorted(changed) == [
        ".agents/skills/weekly-review",
        "system/supervisord.conf.d/notes-indexer.conf",
        "system/supervisord.conf.d/notes.conf",
    ]
    assert existing_derived_paths(tmp_path, package) == ("system/supervisord.conf.d/notes.conf",)
    assert not os.path.lexists(tmp_path / ".agents" / "skills" / "weekly-review")
    assert neighbour.read_text() == "[program:share-gateway]\ncommand=share-gateway\n"
    assert "startsecs=30" in main_conf.read_text()


def _supervisord_environment(line: str) -> dict[str, str]:
    """An ``environment=`` value as supervisord reads it: quoted tokens with no escapes, percent signs doubled."""
    lexer = shlex.shlex(line.removeprefix("environment=").replace("%%", "%"))
    lexer.wordchars += "/.+-():"
    tokens = list(lexer)
    return {tokens[index]: tokens[index + 2].strip("'\"") for index in range(0, len(tokens), 4)}


def test_arguments_and_environment_values_reach_the_program_exactly_as_the_manifest_wrote_them(
    tmp_path: Path,
) -> None:
    awkward_arguments = ['It\'s 100% "notes"', "two words", "$HOME", "back\\slash", "semi;colon && more", "`tick`"]
    arguments_toml = ", ".join(_toml(argument) for argument in awkward_arguments)
    extra = (
        f'\n[run]\ncommand = "printf"\nargs = ["%s|", {arguments_toml}]\n'
        'env = { SHELF_NOTE = "it\'s 50%, a,b", SHELF_QUOTE = "say \\"hi\\" twice" }\n'
    )
    _, _, _, derived = _derive(tmp_path, "shelf", 8086, extra, is_python=False)
    conf_lines = derived.text_by_path["system/supervisord.conf.d/shelf.conf"].splitlines()
    command_line = next(line for line in conf_lines if line.startswith("command="))
    environment_line = next(line for line in conf_lines if line.startswith("environment="))

    # supervisord splits the command the way a POSIX shell does, after undoubling percent signs, and runs it
    # with no shell; the step after the registration, in the script it hands to bash, is the program itself.
    program_argv = shlex.split(command_line.removeprefix("command=").replace("%%", "%"))
    script = program_argv[-1]
    last_step = "exec " + script.split(" && exec ", 1)[1]
    printed = subprocess.run(["bash", "-c", last_step], capture_output=True, text=True, check=True).stdout

    assert program_argv[-3:-1] == ["bash", "-c"]
    assert printed == "".join(f"{argument}|" for argument in awkward_arguments)
    assert _supervisord_environment(environment_line) == {
        "SHELF_NOTE": "it's 50%, a,b",
        "SHELF_QUOTE": 'say "hi" twice',
    }


def _toml(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
