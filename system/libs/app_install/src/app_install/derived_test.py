def _derive(repo_root: Path, name: str, port: int, extra_manifest: str = "", is_python: bool = True):
    package = write_user_app(repo_root, name, extra_manifest, is_python)
    manifest = load_manifest(repo_root / "system" / "apps" / package / "app.toml", mode=ManifestReadMode.STRICT)
    record = AppRecord(name=manifest.name, package=package, port=port, origin=AppOrigin.LOCAL)
    return package, record, manifest, derive_files(repo_root, record, manifest)


def test_a_scaffolded_python_app_gets_one_program_that_syncs_registers_and_execs_its_own_script(
    tmp_path: Path,
) -> None:
    _, _, _, derived = _derive(tmp_path, "inbox-status", 8084)

    assert derived.link_target_by_path == {}
