def test_run_services_and_secrets_shape_each_program(tmp_path: Path) -> None:
    _, _, _, derived = _derive(tmp_path, "notes", 8090, _RUN_SERVICES_AND_SECRETS)

    main = derived.text_by_path["system/supervisord.conf.d/notes.conf"]
    indexer = derived.text_by_path["system/supervisord.conf.d/notes-indexer.conf"]
    assert sorted(derived.text_by_path) == [
        "system/supervisord.conf.d/notes-indexer.conf",
        "system/supervisord.conf.d/notes.conf",
    ]
    assert [line for line in main.splitlines() if line.startswith(("command=", "environment="))] == snapshot(
        [
            'command=python3 system/services/oom_priority/bin/oom_tag_service.py user bash -c "python3 system/scripts/workspace_bare_scripts/venv_links.py ensure-project system/apps/notes && uv sync --locked --project system/apps/notes && python3 system/scripts/forward_port.py --manifest system/apps/notes/app.toml --url http://localhost:8090 && exec python3 system/scripts/with_secrets.py data/.secrets/notes.env -- python3 system/scripts/with_secrets.py data/.secrets/notes-mail.env -- system/apps/notes/.venv/bin/notes-server --listen 127.0.0.1:8090 --title \'It\'\\"\'\\"\'s 100%% \\"notes\\"\'"',
            'environment=NOTES_GREETING=\'say "hi", 100%%\',NOTES_PORT="8090"',
        ]
    )
    assert [
        line for line in indexer.splitlines() if line.startswith(("[program", "command=", "environment="))
    ] == snapshot(
        [
            "[program:notes-indexer]",
            'command=python3 system/services/oom_priority/bin/oom_tag_service.py user bash -c "python3 system/scripts/workspace_bare_scripts/venv_links.py ensure-project system/apps/notes && uv sync --locked --project system/apps/notes && exec python3 system/scripts/with_secrets.py data/.secrets/notes.env -- python3 system/scripts/with_secrets.py data/.secrets/notes-mail.env -- system/apps/notes/.venv/bin/notes-indexer --api http://127.0.0.1:8090"',
        ]
    )


