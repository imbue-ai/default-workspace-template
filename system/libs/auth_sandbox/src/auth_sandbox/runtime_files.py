"""The files under the sandbox's tmpfs: where each one is, and how a key is read."""

from pathlib import Path

from imbue.imbue_common.frozen_model import FrozenModel
from imbue.mngr_latchkey.core import (
    BROWSER_STATE_FILENAME,
    CREDENTIALS_STORE_FILENAME,
    UPSTREAM_DATA_FORMAT_VERSION_FILENAME,
)
from pydantic import Field, SecretStr

from auth_sandbox.errors import MissingMaterialError
from auth_sandbox.primitives import (
    EXPORT_DIRNAME,
    INCOMING_DIRNAME,
    LATCHKEY_DIRNAME,
    LATCHKEY_KEY_FILENAME,
    RUNTIME_DIR,
    TRANSFER_KEY_FILENAME,
)


class SandboxPaths(FrozenModel):
    """The layout under the sandbox's runtime directory (``/run/auth-sandbox`` in the image)."""

    runtime_dir: Path = Field(
        default=RUNTIME_DIR,
        description="The tmpfs root every user-specific file lives under",
    )

    @property
    def latchkey_key_path(self) -> Path:
        """The sandbox's own latchkey encryption key, generated by the boot script."""
        return self.runtime_dir / LATCHKEY_KEY_FILENAME

    @property
    def transfer_key_path(self) -> Path:
        """The dialog's one-time transfer key, written by the chrome over owner-exec."""
        return self.runtime_dir / TRANSFER_KEY_FILENAME

    @property
    def incoming_dir(self) -> Path:
        """Where the chrome writes the workspace machine's browser state, encrypted under the transfer key."""
        return self.runtime_dir / INCOMING_DIRNAME

    @property
    def incoming_browser_state_path(self) -> Path:
        return self.incoming_dir / BROWSER_STATE_FILENAME

    @property
    def export_dir(self) -> Path:
        """Where ``auth-sandbox-export`` writes the bundle the chrome reads back."""
        return self.runtime_dir / EXPORT_DIRNAME

    @property
    def latchkey_directory(self) -> Path:
        """The sandbox's ``LATCHKEY_DIRECTORY``: the template config, and the credentials a sign-in stores."""
        return self.runtime_dir / LATCHKEY_DIRNAME

    @property
    def latchkey_browser_state_path(self) -> Path:
        return self.latchkey_directory / BROWSER_STATE_FILENAME

    @property
    def exported_credentials_path(self) -> Path:
        return self.export_dir / CREDENTIALS_STORE_FILENAME

    @property
    def exported_data_format_version_path(self) -> Path:
        return self.export_dir / UPSTREAM_DATA_FORMAT_VERSION_FILENAME

    @property
    def exported_browser_state_path(self) -> Path:
        return self.export_dir / BROWSER_STATE_FILENAME


def read_key(path: Path) -> SecretStr:
    """A base64 key as the boot script or the chrome wrote it, without the trailing newline.

    Raises:
        MissingMaterialError: when the file is absent or empty, naming the path and nothing of its contents.
    """
    try:
        text = path.read_text(encoding="utf-8").strip()
    except FileNotFoundError as e:
        raise MissingMaterialError(f"no key at {path}") from e
    except OSError as e:
        raise MissingMaterialError(
            f"the key at {path} cannot be read: {e.strerror}"
        ) from e
    if not text:
        raise MissingMaterialError(f"the key file at {path} is empty")
    return SecretStr(text)
