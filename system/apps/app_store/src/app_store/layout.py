"""Where an installed app's files go, and the two files the store generates for it: its app.toml and its supervisord
drop-in.

Each installed app has one folder under the store's data folder::

    data/.apps/app-store/<slug>/
        env/           its environment (rebuildable, so kept out of the backup)
        data/          its own data: notebooks, databases, flows, settings
        app.toml       its generated manifest, naming icon.svg beside it
        icon.svg       its icon, copied from the catalog
        install.log    the raw log of the last install, repair or uninstall

and one supervisord drop-in, ``system/supervisord.conf.d/<slug>.conf``, which runs ``app-store-launch <slug>``. The
drop-ins are gitignored (the catalog's slugs are listed in .gitignore) and re-created from the install records when
the store starts, so an install survives a rebuild of the workspace's code.
"""

import json
from pathlib import Path
from typing import Final

from pydantic import Field

from app_store.catalog import CatalogApp
from imbue.imbue_common.frozen_model import FrozenModel
from imbue.imbue_common.pure import pure

ENV_DIRNAME: Final[str] = "env"
# Where an update sets the running version's environment aside until the new one starts.
PREVIOUS_ENV_DIRNAME: Final[str] = "env.previous"
APP_DATA_DIRNAME: Final[str] = "data"
MANIFEST_FILENAME: Final[str] = "app.toml"
ICON_FILENAME: Final[str] = "icon.svg"
INSTALL_LOG_FILENAME: Final[str] = "install.log"
# Written into the environment folder so the hourly backup skips it (harden-creation.md, "Keep rebuildable data out
# of the backup").
NO_BACKUP_MARKER: Final[str] = ".nobackup"
# Written into the app's data folder once its init command has run.
INITIALIZED_MARKER: Final[str] = ".app-store-initialized"
# Run from the workspace venv, where ``uv sync --all-packages`` installs every built-in app's console scripts.
LAUNCH_SCRIPT: Final[str] = ".venv/bin/app-store-launch"
OOM_TAG_SCRIPT: Final[str] = "system/services/oom_priority/bin/oom_tag_service.py"
# A user-installed app is shed before any built-in under memory pressure.
INSTALLED_APP_PRIORITY: Final[str] = "user"
GENERATED_MARKER: Final[str] = "# Generated by the App Store"


class StoreLayout(FrozenModel):
    """The folders the store works in, all absolute."""

    data_dir: Path = Field(description="The store's own data folder (installs.json and one folder per app)")
    repo_root: Path = Field(description="The workspace checkout every supervised program runs from")

    @property
    def records_path(self) -> Path:
        return self.data_dir / "installs.json"

    @property
    def added_apps_path(self) -> Path:
        return self.data_dir / "added-apps.json"

    @property
    def pending_repo_adds_path(self) -> Path:
        return self.data_dir / "pending-repo-adds.json"

    @property
    def dropin_dir(self) -> Path:
        return self.repo_root / "system" / "supervisord.conf.d"

    @property
    def supervisord_conf(self) -> Path:
        return self.repo_root / "system" / "supervisord.conf"

    def app_dir(self, slug: str) -> Path:
        return self.data_dir / slug

    def env_dir(self, slug: str) -> Path:
        return self.app_dir(slug) / ENV_DIRNAME

    def previous_env_dir(self, slug: str) -> Path:
        return self.app_dir(slug) / PREVIOUS_ENV_DIRNAME

    def app_data_dir(self, slug: str) -> Path:
        return self.app_dir(slug) / APP_DATA_DIRNAME

    def manifest_path(self, slug: str) -> Path:
        return self.app_dir(slug) / MANIFEST_FILENAME

    def icon_path(self, slug: str) -> Path:
        return self.app_dir(slug) / ICON_FILENAME

    def log_path(self, slug: str) -> Path:
        return self.app_dir(slug) / INSTALL_LOG_FILENAME

    def dropin_path(self, slug: str) -> Path:
        return self.dropin_dir / f"{slug}.conf"


@pure
def render_manifest(app: CatalogApp) -> str:
    """The installed app's app.toml: what the desktop shows for it, and that the shell may stop it once no window
    shows it (the store's apps answer requests and do nothing in between)."""
    lines = [
        f"{GENERATED_MARKER} from its catalog entry for {app.title} {app.version}.",
        f"name = {json.dumps(app.slug)}",
        f"display_name = {json.dumps(app.title)}",
        f"description = {json.dumps(app.description)}",
        f"icon = {json.dumps(ICON_FILENAME)}",
        f"priority = {json.dumps(INSTALLED_APP_PRIORITY)}",
        f"program = {json.dumps(app.slug)}",
        "stop_when_no_windows = true",
        "",
    ]
    return "\n".join(lines)


@pure
def render_dropin(app: CatalogApp, repo_root: Path) -> str:
    """The installed app's supervisord program: tagged into the user band, it runs the store's launcher, which
    registers the app's manifest and port with forward_port.py and then execs the app's own launch command."""
    return "\n".join(
        [
            f"{GENERATED_MARKER} for {app.title} {app.version} (system/apps/app_store).",
            "# Not saved with the workspace's code: the store re-creates it from data/.apps/app-store/installs.json",
            "# when it starts. Uninstall the app from the App Store rather than deleting this file.",
            f"[program:{app.slug}]",
            f"command=python3 {OOM_TAG_SCRIPT} {INSTALLED_APP_PRIORITY} {LAUNCH_SCRIPT} {app.slug}",
            f"directory={repo_root}",
            "autostart=true",
            "autorestart=true",
            "startsecs=10",
            "startretries=5",
            "stopasgroup=true",
            "killasgroup=true",
            f"stdout_logfile=/var/log/supervisor/{app.slug}-stdout.log",
            f"stderr_logfile=/var/log/supervisor/{app.slug}-stderr.log",
            "stdout_logfile_maxbytes=10MB",
            "stderr_logfile_maxbytes=10MB",
            "stdout_logfile_backups=3",
            "stderr_logfile_backups=3",
            "",
        ]
    )


def is_store_dropin(path: Path) -> bool:
    """Whether the drop-in at ``path`` was written by the store (and so may be rewritten or removed by it)."""
    try:
        return path.read_text(encoding="utf-8").startswith(GENERATED_MARKER)
    except OSError:
        return False
