"""Chromium launch arguments for the browser fleet.

Ported from browser-use 0.13.1 (`browser_use/browser/profile.py`) when that dependency
was removed, and deliberately NOT re-derived from Playwright's own switch list.

The distinction matters and is easy to get backwards. Playwright's
`chromiumSwitches.ts` adds `--enable-automation` (which sets `navigator.webdriver = true`)
and `--disable-extensions` / `--disable-component-extensions-with-background-pages`
(which kill unpacked extensions on Chrome 145+). browser-use's list is a FORK of
Playwright's with exactly those removed -- see `_STRIPPED_FROM_PLAYWRIGHT` -- and that
subtraction is the thing the fleet actually needs: Fortress is a stealth build whose
entire point is not announcing itself, and the fleet loads unpacked extensions.

So this module is the curated list, kept as data. Anything added here should be checked
against those two constraints.
"""

