# The fleet's own additions, on top of the ported list. These were already passed
# alongside browser-use's defaults, so they are part of the effective command line
# that runs today.
_FLEET_ARGS = (
    # Chromium blocklists --no-sandbox (which we must pass as root) and pins a permanent
    # "unsupported command-line flag" infobar above every page for it. We film Chrome's
    # real window, so the human would see that bar for the life of the browser.
    # --test-type is the only supported suppression that does not break stealth:
    # infobar_utils.cc skips the whole bad-flags prompt when it (or --enable-automation,
    # which is not an option here) is present. It disables Chrome's own background
    # *component* extensions; unpacked ones are unaffected, and page JS cannot see it.
    "--test-type",
    "--disable-gpu-compositing",
    "--disable-smooth-scrolling",
    "--wm-window-animations-disabled",
    "--force-prefers-reduced-motion",
    "--renderer-process-limit=4",
    "--no-first-run",
    "--disable-session-crashed-bubble",
    "--hide-crash-restore-bubble",
    "--disable-dev-shm-usage",
    # Maps the (0,0,w,h) capture region 1:1 to window pixels so the human's input
    # coordinates stay correct. Load-bearing for the streaming path.
    "--window-position=0,0",
)


def launch_args(
    *,
    user_data_dir: str,
    remote_debugging_port: int = 0,
    window_size: "tuple[int, int] | None" = None,
    extensions: "tuple[str, ...]" = (),
    no_sandbox: bool = False,
) -> "list[str]":
    """The full Chromium argv (excluding the executable and the start URL).

    There is no viewport emulation here on purpose: the page must fill the real OS
    window so a pane resize reflows it, which is what browser-use's `no_viewport=True`
    bought. A fixed viewport would render at a constant size and letterbox the capture.
    """
    args = [
        *_BASE_ARGS,
        f"--disable-features={','.join(DISABLED_COMPONENTS)}",
        *_FLEET_ARGS,
        f"--user-data-dir={user_data_dir}",
        f"--remote-debugging-port={remote_debugging_port}",
    ]
    if window_size is not None:
        args.append(f"--window-size={window_size[0]},{window_size[1]}")
    if extensions:
        args.append(f"--load-extension={','.join(extensions)}")
    if no_sandbox:
        args.append("--no-sandbox")
    assert not (set(args) & set(_STRIPPED_FROM_PLAYWRIGHT)), "a Playwright anti-stealth switch leaked in"
    return args
