# The Screen's own additions.
_SCREEN_ARGS: Final[tuple[str, ...]] = (
    # Chromium blocklists --no-sandbox (which it is passed as root) and pins a permanent "unsupported
    # command-line flag" infobar above every page for it. --test-type is the only supported suppression that
    # does not break stealth: infobar_utils.cc skips the whole bad-flags prompt when it is present. It disables
    # Chrome's own background component extensions; unpacked ones are unaffected, and page JS cannot see it.
    "--test-type",
    "--disable-gpu-compositing",
    "--disable-smooth-scrolling",
    "--wm-window-animations-disabled",
    "--force-prefers-reduced-motion",
    "--renderer-process-limit=4",
    "--disable-session-crashed-bubble",
    # Declare English rather than inheriting whatever locale the image has: --lang sets Chrome's UI locale,
    # --accept-lang the Accept-Language header outright. Google ignores both for its consent interstitial (it
    # geolocates the egress IP); the lever there is hl=en in the URL.
    "--lang=en-US",
    "--accept-lang=en-US,en",
    # Chromium's window fills the Screen: the Screen is sized to the controller's window (spec section 7.2), often
    # smaller than Chromium's default or the bounds its profile remembers, and xfwm4 never shrinks a window that is
    # larger than the display. A maximized window also follows the Screen's later size changes.
    "--start-maximized",
)


@pure
def launch_args(
    user_data_dir: str,
    remote_debugging_port: int,
    extensions: Sequence[str],
    is_sandbox_disabled: bool,
) -> list[str]:
    """The full Chromium argv (excluding the executable and the start URL).

    No viewport emulation: the page fills the real X window, maximized to the Screen, so a resize of the Screen
    reflows it.
    """
    arguments = [
        *_BASE_ARGS,
        f"--disable-features={','.join(DISABLED_COMPONENTS)}",
        *_SCREEN_ARGS,
        f"--user-data-dir={user_data_dir}",
        f"--remote-debugging-port={remote_debugging_port}",
    ]
    if extensions:
        arguments.append(f"--load-extension={','.join(extensions)}")
    if is_sandbox_disabled:
        arguments.append("--no-sandbox")
    assert not (set(arguments) & set(STRIPPED_FROM_PLAYWRIGHT)), "a Playwright anti-stealth switch leaked in"
    return arguments
