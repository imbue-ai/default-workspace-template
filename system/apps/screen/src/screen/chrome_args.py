# Playwright default switches that must never be emitted, kept as data so the reason is greppable.
STRIPPED_FROM_PLAYWRIGHT: Final[tuple[str, ...]] = (
    # Sets navigator.webdriver=true, which defeats Fortress's whole purpose.
    "--enable-automation",
    # The Screen loads uBlock Origin Lite and the cookie-banner extension unpacked.
    "--disable-extensions",
    # Kills unpacked extensions on Chrome 145+.
    "--disable-component-extensions-with-background-pages",
    # Scrollbars tell an agent there is more to scroll.
    "--hide-scrollbars",
)

