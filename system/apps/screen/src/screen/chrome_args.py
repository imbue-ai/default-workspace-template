"""Chromium's launch arguments, kept as data.

Ported from browser-use 0.13.1 (``browser_use/browser/profile.py``), deliberately not re-derived from Playwright's
own switch list: Playwright's ``chromiumSwitches.ts`` adds ``--enable-automation`` (``navigator.webdriver`` true)
and ``--disable-extensions`` (which kills unpacked extensions on Chrome 145+), and browser-use's list is a fork of
it with exactly those removed. Fortress is a stealth build whose point is not announcing itself, and the Screen
loads unpacked extensions, so that subtraction is what this list keeps. Anything added here is checked against
those two constraints.
"""

